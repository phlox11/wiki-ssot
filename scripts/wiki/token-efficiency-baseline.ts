function run(command: string[], cwd: string, extraEnvironment: Record<string, string> = {}): CommandResult {
  const result = Bun.spawnSync(command, {
    cwd,
    env: { ...process.env, ...extraEnvironment },
    stdout: "pipe",
    stderr: "pipe",
  });
  return { exitCode: result.exitCode, stdout: result.stdout.toString(), stderr: result.stderr.toString() };
}

function required(command: string[], cwd: string, extraEnvironment: Record<string, string> = {}): CommandResult {
  const result = run(command, cwd, extraEnvironment);
  if (result.exitCode !== 0) throw new Error(`${command.join(" ")} failed\n${result.stderr || result.stdout}`);
  return result;
}

function git(root: string, args: string[], allowFailure = false): string {
  return required(["git", ...args], root, allowFailure ? {} : {}).stdout.trim();
}

function metric(text: string): TextMetric {
  const trimmed = text.trim();
  return {
    lines: (text.match(/\n/g) ?? []).length,
    words: trimmed.length === 0 ? 0 : trimmed.split(/\s+/).length,
    bytes: Buffer.byteLength(text, "utf8"),
  };
}

function sumMetrics(metrics: TextMetric[]): TextMetric {
  return metrics.reduce((sum, item) => ({
    lines: sum.lines + item.lines,
    words: sum.words + item.words,
    bytes: sum.bytes + item.bytes,
  }), { lines: 0, words: 0, bytes: 0 });
}

function sortedPaths(root: string, relativeRoot: string, suffix?: string): string[] {
  const absolute = join(root, relativeRoot);
  if (!existsSync(absolute)) return [];
  const output: string[] = [];
  const visit = (path: string) => {
    for (const entry of readdirSync(path, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const child = join(path, entry.name);
      if (entry.isDirectory()) visit(child);
      else if (!suffix || child.endsWith(suffix)) output.push(relative(root, child).replaceAll("\\", "/"));
    }
  };
  if (statSync(absolute).isDirectory()) visit(absolute);
  else if (!suffix || absolute.endsWith(suffix)) output.push(relative(root, absolute).replaceAll("\\", "/"));
  return output.sort((a, b) => a.localeCompare(b));
}

function summarizeContext(value: unknown): SemanticCounts {
  const object = value as Record<string, unknown>;
  const pages = Array.isArray(object.pages) ? object.pages as Record<string, unknown>[] : [];
  const nonCurrent = Array.isArray(object.nonCurrentPages) ? object.nonCurrentPages as Record<string, unknown>[] : [];
  const conflicts = Array.isArray(object.conflicts) ? object.conflicts as Record<string, unknown>[] : [];
  const sources = Array.isArray(object.sources) ? object.sources as Record<string, unknown>[] : [];
  const sourceFiles = new Set<string>();
  const sourceIds = sources.flatMap((item) => typeof item.pageId === "string" ? [item.pageId] : []);
  const sourceDeclarationCount = sources.reduce((count, item) => count + (Array.isArray(item.declared) ? item.declared.length : 0), 0);
  for (const source of [...pages, ...nonCurrent, ...sources]) {
    for (const path of Array.isArray(source.sourceFiles) ? source.sourceFiles : []) if (typeof path === "string") sourceFiles.add(path);
  }
  return {
    pageCount: pages.length,
    currentPageCount: pages.filter((page) => page.status === "current").length,
    nonCurrentPageCount: nonCurrent.length,
    conflictCount: conflicts.length,
    sourceDeclarationCount,
    sourceFileCount: sourceFiles.size,
    readOrderCount: Array.isArray(object.readOrder) ? object.readOrder.length : 0,
    sourceIds: [...new Set(sourceIds)].sort((a, b) => a.localeCompare(b)),
    pageIds: pages.flatMap((page) => typeof page.id === "string" ? [page.id] : []).sort((a, b) => a.localeCompare(b)),
    nonCurrentPageIds: nonCurrent.flatMap((page) => typeof page.id === "string" ? [page.id] : []).sort((a, b) => a.localeCompare(b)),
    conflictIds: conflicts.flatMap((conflict) => typeof conflict.id === "string" ? [conflict.id] : []).sort((a, b) => a.localeCompare(b)),
  };
}

function cli(root: string, args: string[]): CommandResult {
  return run([process.execPath, join(root, "scripts/wiki/cli.ts"), ...args], root);
}

function requiredCli(root: string, args: string[]): CommandResult {
  const result = cli(root, args);
  if (result.exitCode !== 0) throw new Error(`wiki ${args.join(" ")} failed\n${result.stderr || result.stdout}`);
  return result;
}

function entryMeasurement(root: string): EntryMeasurement {
  const files = Object.fromEntries(TOKEN_EFFICIENCY_ENTRY_PATHS.map((path) => [path, metric(readFileSync(join(root, path), "utf8"))]));
  const text = sumMetrics(Object.values(files));
  const json = metric(jsonStable({ paths: [...TOKEN_EFFICIENCY_ENTRY_PATHS], files }));
  return {
    paths: [...TOKEN_EFFICIENCY_ENTRY_PATHS],
    files,
    text,
    json,
    semantic: { fileCount: 4, sourcePathCount: 4, currentAuthorityFileCount: 1 },
  };
}

function contextMeasurement(root: string, label: ContextMeasurement["label"], query: string | null, workId: string | null): ContextMeasurement {
  const args = workId == null ? ["context", query!, "--json"] : ["context", "--work", workId, "--json"];
  const jsonResult = requiredCli(root, args);
  const value = JSON.parse(jsonResult.stdout) as unknown;
  const textResult = workId == null
    ? requiredCli(root, ["context", query!])
    : requiredCli(root, ["context", "--work", workId]);
  return { label, query, workId, text: metric(textResult.stdout), json: metric(jsonResult.stdout), semantic: summarizeContext(value) };
}

function recursiveSourceMeasurement(root: string): RecursiveSourceMeasurement {
  // The runner is publishing-only evidence and did not exist at the pinned
  // context revision. Exclude its copied historical launcher from the source
  // boundary so the reproduction remains the exact 22-file expansion.
  const paths = sortedPaths(root, "scripts/wiki", ".ts")
    .filter((path) => path !== "scripts/wiki/token-efficiency-baseline.ts");
  const files = paths.map((path) => metric(readFileSync(join(root, path), "utf8")));
  return { glob: TOKEN_EFFICIENCY_SOURCE_GLOB, paths, fileCount: paths.length, text: sumMetrics(files) };
}

