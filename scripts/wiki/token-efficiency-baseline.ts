function isFiniteNonNegativeInteger(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && Number.isInteger(value) && value >= 0;
}

function forbiddenRolloutKey(key: string): boolean {
  return /(transcript|prompt|private.?path|session.?path|thread.?id|session.?id|absolute.?path|file.?path|working.?directory)/i.test(key);
}

function scanForbiddenValues(value: unknown, path = "rollout"): string[] {
  if (Array.isArray(value)) return value.flatMap((item, index) => scanForbiddenValues(item, `${path}[${index}]`));
  if (value == null || typeof value !== "object") return [];
  const errors: string[] = [];
  for (const [key, child] of Object.entries(value as Record<string, unknown>)) {
    if (forbiddenRolloutKey(key)) errors.push(`${path}.${key} is not permitted in sanitized rollout input`);
    errors.push(...scanForbiddenValues(child, `${path}.${key}`));
  }
  return errors;
}

// Accept the two common neutral spellings used by local usage exporters while
// emitting one canonical, versioned shape. The aliases carry no additional
// information and are normalized before accounting is checked.
const TOKEN_FIELD_ALIASES: Record<string, string[]> = {
  rawInputTokens: ["rawInputTokens", "inputTokens", "rawInput"],
  cachedInputTokens: ["cachedInputTokens", "cachedInput"],
  uncachedInputTokens: ["uncachedInputTokens", "derivedUncachedInputTokens", "uncachedInput"],
  outputTokens: ["outputTokens", "output"],
  reasoningOutputTokens: ["reasoningOutputTokens", "reasoningOutput"],
  totalTokens: ["totalTokens", "total"],
};

function normalizeTokenFields(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(normalizeTokenFields);
  if (value == null || typeof value !== "object") return value;
  const object = value as Record<string, unknown>;
  const normalized: Record<string, unknown> = { ...object };
  for (const [canonical, aliases] of Object.entries(TOKEN_FIELD_ALIASES)) {
    if (normalized[canonical] !== undefined) continue;
    const alias = aliases.find((key) => normalized[key] !== undefined);
    if (alias != null) normalized[canonical] = normalized[alias];
  }
  if (Array.isArray(normalized.agents)) normalized.agents = normalized.agents.map(normalizeTokenFields);
  if (normalized.totals != null) normalized.totals = normalizeTokenFields(normalized.totals);
  return normalized;
}

function rolloutAgent(value: unknown, index: number, errors: string[]): ControlledRolloutAgent | undefined {
  if (value == null || typeof value !== "object" || Array.isArray(value)) {
    errors.push(`agents[${index}] must be an object`);
    return undefined;
  }
  const item = value as Record<string, unknown>;
  const strings = ["taskLabel", "role", "model", "effort"];
  for (const key of strings) if (typeof item[key] !== "string" || String(item[key]).trim().length === 0) errors.push(`agents[${index}].${key} must be a non-empty string`);
  const numbers = ["modelCallCount", "rawInputTokens", "cachedInputTokens", "uncachedInputTokens", "outputTokens", "reasoningOutputTokens", "totalTokens"] as const;
  for (const key of numbers) if (!isFiniteNonNegativeInteger(item[key])) errors.push(`agents[${index}].${key} must be a finite non-negative integer`);
  if (errors.some((error) => error.startsWith(`agents[${index}]`))) return undefined;
  const agent = item as unknown as ControlledRolloutAgent;
  if (agent.modelCallCount < 1) errors.push(`agents[${index}].modelCallCount must be at least one`);
  if (agent.cachedInputTokens > agent.rawInputTokens) errors.push(`agents[${index}].cachedInputTokens cannot exceed rawInputTokens`);
  if (agent.uncachedInputTokens !== agent.rawInputTokens - agent.cachedInputTokens) errors.push(`agents[${index}].uncachedInputTokens must equal rawInputTokens - cachedInputTokens`);
  if (agent.reasoningOutputTokens > agent.outputTokens) errors.push(`agents[${index}].reasoningOutputTokens cannot exceed outputTokens`);
  if (agent.totalTokens !== agent.rawInputTokens + agent.outputTokens) errors.push(`agents[${index}].totalTokens must equal rawInputTokens + outputTokens`);
  return { ...agent };
}

function aggregateAgents(agents: ControlledRolloutAgent[]): ControlledRolloutTotals {
  return {
    agentCount: agents.length,
    modelCallCount: agents.reduce((sum, item) => sum + item.modelCallCount, 0),
    rawInputTokens: agents.reduce((sum, item) => sum + item.rawInputTokens, 0),
    cachedInputTokens: agents.reduce((sum, item) => sum + item.cachedInputTokens, 0),
    uncachedInputTokens: agents.reduce((sum, item) => sum + item.uncachedInputTokens, 0),
    outputTokens: agents.reduce((sum, item) => sum + item.outputTokens, 0),
    reasoningOutputTokens: agents.reduce((sum, item) => sum + item.reasoningOutputTokens, 0),
    totalTokens: agents.reduce((sum, item) => sum + item.totalTokens, 0),
  };
}

export function inspectControlledRollout(input: unknown): RolloutValidation {
  const errors = scanForbiddenValues(input);
  if (input == null || typeof input !== "object" || Array.isArray(input)) return { ok: false, errors: [...errors, "rollout must be an object"] };
  const value = normalizeTokenFields(input) as Record<string, unknown>;
  if (value.version !== 1) errors.push("rollout.version must be 1");
  if (value.kind !== "sanitized-controlled-rollout") errors.push("rollout.kind must be sanitized-controlled-rollout");
  const comparison = value.comparison;
  if (comparison == null || typeof comparison !== "object" || Array.isArray(comparison)) errors.push("rollout.comparison must be an object");
  else {
    for (const key of ["taskLabel", "contextSourceRevision", "orchestration"]) if (typeof (comparison as Record<string, unknown>)[key] !== "string" || String((comparison as Record<string, unknown>)[key]).trim().length === 0) errors.push(`rollout.comparison.${key} must be a non-empty string`);
  }
  if (value.provenance != null && (typeof value.provenance !== "object" || Array.isArray(value.provenance))) errors.push("rollout.provenance must be an object");
  const rawAgents = value.agents;
  if (!Array.isArray(rawAgents) || rawAgents.length === 0) errors.push("rollout.agents must be a non-empty array");
  const agents = Array.isArray(rawAgents) ? rawAgents.flatMap((item, index) => { const agent = rolloutAgent(item, index, errors); return agent ? [agent] : []; }) : [];
  const expectedTotals = aggregateAgents(agents);
  const totals = value.totals;
  if (totals == null || typeof totals !== "object" || Array.isArray(totals)) errors.push("rollout.totals must be an object");
  else {
    const suppliedTotals = totals as Record<string, unknown>;
    for (const key of Object.keys(expectedTotals) as (keyof ControlledRolloutTotals)[]) if (suppliedTotals[key] !== expectedTotals[key]) errors.push(`rollout.totals.${key} must equal the aggregate of agents`);
  }
  if (errors.length > 0) return { ok: false, errors };
  return { ok: true, errors: [], rollout: {
    version: 1,
    kind: "sanitized-controlled-rollout",
    comparison: comparison as ControlledRollout["comparison"],
    ...(value.provenance == null ? {} : { provenance: value.provenance as ControlledRollout["provenance"] }),
    agents,
    totals: expectedTotals,
  } };
}

export function validateControlledRollout(input: unknown): ControlledRollout {
  const result = inspectControlledRollout(input);
  if (!result.ok || result.rollout == null) throw new Error(`invalid controlled rollout:\n${result.errors.join("\n")}`);
  return result.rollout;
}

